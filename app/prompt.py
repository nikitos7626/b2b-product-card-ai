def build_user_prompt(
    name: str,
    manufacturer: str,
    specs: Dict[str, Any],
    description: str,
    detected_category: str = "",
    required_specs_hint: str = ""
) -> str:
    """Формирует пользовательский промпт с контекстом прибора и таксономическими подсказками."""
    
    payload = {
        "название_товара": name,
        "производитель": manufacturer or "не указан",
        "характеристики_из_запроса": specs or {},
        "описание_или_паспорт": description or "не предоставлено"
    }
    
    context_hint = ""
    if detected_category:
        context_hint = f"\nОпределенная категория по каталогу: «{detected_category}»."
    if required_specs_hint:
        context_hint += f"\nОбязательные атрибуты для данной категории: {required_specs_hint}."
    
    return f"""Составь черновик карточки товара по следующим входным данным:{context_hint}

ВХОДНЫЕ ДАННЫЕ (JSON):
{json.dumps(payload, ensure_ascii=False, indent=2)}

ПОМНИ ПРАВИЛА:
1. Заголовок seo_title <= 70 символов.
2. Текст seo_description от 800 до 1200 символов.
3. Никаких выдуманных параметров — если параметра нет во входе, пиши 'данных нет'.
4. Верни чистый структурированный JSON.
"""
