def run_batch_test():
    base_dir = Path(__file__).resolve().parent
    results = []
    
    print(f"Запуск сквозного тестирования 20 категорий приборов...")
    print("=" * 80)
    
    passed_count = 0
    total_count = len(TEST_PRODUCTS)
    
    start_time = time.time()
    
    for idx, p_data in enumerate(TEST_PRODUCTS, 1):
        p_input = ProductInput.model_validate(p_data)
        item_start = time.time()
        
        try:
            res = card_service.generate_product_card(p_input)
            item_duration = time.time() - item_start
            
            # Проверки требований
            t_len = res.seo_title_length
            d_len = res.seo_description_length
            q_cnt = len(res.search_queries)
            s_cnt = len(res.key_specs)
            
            title_ok = t_len <= 70
            desc_ok = (800 <= d_len <= 1200)
            queries_ok = (3 <= q_cnt <= 5)
            specs_ok = (s_cnt >= 4)
            commercial_ok = bool(res.commercial_block.target_audience and res.commercial_block.tasks_solved)
            
            all_ok = title_ok and desc_ok and queries_ok and specs_ok and commercial_ok
            if all_ok:
                passed_count += 1
                status_icon = "✅ PASS"
            else:
                status_icon = "⚠️ WARN"
                
            report_row = {
                "index": idx,
                "name": p_input.name,
                "category": res.data_quality.detected_category,
                "title": res.seo_title,
                "title_len": t_len,
                "title_ok": title_ok,
                "desc_len": d_len,
                "desc_ok": desc_ok,
                "queries_count": q_cnt,
                "queries_ok": queries_ok,
                "specs_count": s_cnt,
                "specs_ok": specs_ok,
                "duration_sec": round(item_duration, 2),
                "status": "PASS" if all_ok else "WARN"
            }
            results.append(report_row)
            
            print(f"[{idx:02d}/20] {status_icon} | {p_input.name[:40]:<40} | Title: {t_len:2d}/70 | Desc: {d_len:4d}/800-1200 | Queries: {q_cnt} | Specs: {s_cnt} | {item_duration:.2f}s")
            
        except Exception as e:
            print(f"[{idx:02d}/20] ❌ FAIL | {p_input.name[:40]:<40} | Error: {e}")
            results.append({
                "index": idx,
                "name": p_input.name,
                "status": "FAIL",
                "error": str(e)
            })

    total_duration = time.time() - start_time
    print("=" * 80)
    print(f"РЕЗУЛЬТАТ: {passed_count}/{total_count} тестов успешно пройдено ({passed_count/total_count*100:.1f}%) за {total_duration:.1f} сек.")
    
    # Сохраняем отчеты в output/
    out_dir = base_dir / "output"
    out_dir.mkdir(parents=True, exist_ok=True)
    
    with open(out_dir / "batch_20_categories_report.json", "w", encoding="utf-8") as f:
        json.dump({
            "total": total_count,
            "passed": passed_count,
            "success_rate": round(passed_count / total_count * 100, 1),
            "total_duration_sec": round(total_duration, 2),
            "results": results
        }, f, ensure_ascii=False, indent=2)

    # Генерация Markdown-таблицы
    md_lines = [
        "# Отчёт по тестированию генерации карточек по 20 категориям товаров",
        "",
        f"- **Всего категорий протестировано:** {total_count}",
        f"- **Успешно соответствуют всем критериям:** {passed_count} ({passed_count/total_count*100:.1f}%)",
        f"- **Общее время генерации:** {total_duration:.1f} с (в среднем {total_duration/total_count:.2f} с на карточку)",
        "",
        "## Сводная таблица результатов",
        "",
        "| № | Прибор | Категория | Title (знаков) | Description (знаков) | Запросы | Характеристики | Время | Статус |",
        "|---|---|---|---|---|---|---|---|---|"
    ]
    for r in results:
        if r.get("status") == "FAIL":
            md_lines.append(f"| {r['index']} | {r['name']} | — | — | — | — | — | — | ❌ FAIL ({r.get('error')}) |")
        else:
            t_mark = "✅" if r["title_ok"] else f"⚠️ {r['title_len']}"
            d_mark = "✅" if r["desc_ok"] else f"⚠️ {r['desc_len']}"
            q_mark = "✅" if r["queries_ok"] else f"⚠️ {r['queries_count']}"
            md_lines.append(f"| {r['index']} | {r['name']} | {r['category']} | {r['title_len']} {t_mark} | {r['desc_len']} {d_mark} | {r['queries_count']} {q_mark} | {r['specs_count']} ✅ | {r['duration_sec']} с | {r['status']} |")

    with open(out_dir / "batch_20_categories_report.md", "w", encoding="utf-8") as f:
        f.write("\n".join(md_lines))
        
    print(f"\nОтчёты сохранены в:")
    print(f" - {out_dir / 'batch_20_categories_report.md'}")
    print(f" - {out_dir / 'batch_20_categories_report.json'}")

if __name__ == "__main__":
    run_batch_test()
